// Multi-language translation dictionaries
let currentLang = 'th';
try {
    currentLang = localStorage.getItem('schedule_lang');
    if (!currentLang || (currentLang !== 'th' && currentLang !== 'en')) {
        const nav =
            typeof window !== 'undefined'
                ? window.navigator
                : typeof navigator !== 'undefined'
                  ? navigator
                  : null;
        const navLang = nav ? nav.language || (nav.languages && nav.languages[0]) || '' : '';
        currentLang = navLang.toLowerCase().startsWith('th') ? 'th' : 'en';
        localStorage.setItem('schedule_lang', currentLang);
    }
} catch (e) {
    currentLang = 'en'; // Safe fallback if localStorage is disabled
}

const SHORTAGE_MARKER = '__SHORTAGE__';
const esc = (str) => {
    if (typeof str !== 'string') return str;
    return str.replace(/[&<>"']/g, function (m) {
        switch (m) {
            case '&':
                return '&amp;';
            case '<':
                return '&lt;';
            case '>':
                return '&gt;';
            case '"':
                return '&quot;';
            case "'":
                return '&#39;';
        }
    });
};

// Doctor and role names live in "name:role, A:B" text formats, so strip the separators.
const sanitizeName = (raw) => {
    const n = String(raw ?? '')
        .replace(/[\u200b-\u200d\ufeff]/g, '')
        .replace(/[:;,/\r\n]+/g, ' ')
        .replace(/\s+/g, ' ')
        .trim();
    // '-' and the shortage marker are the empty-slot and shortage markers in the schedule
    return n === '-' || n === '__SHORTAGE__' ? '' : n;
};
// An <input type="date"> value ("YYYY-MM-DD") as local midnight. new Date("YYYY-MM-DD") is UTC
// midnight, which reads as the previous day west of UTC.
const parseISODate = (str) => {
    const [y, m, d] = String(str).split('-').map(Number);
    return new Date(y, m - 1, d);
};
